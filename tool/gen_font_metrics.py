#!/usr/bin/env python3
"""Regenerates lib/src/font/metrics/font_metrics_data.dart from KaTeX.

Usage: python3 tool/gen_font_metrics.py <KaTeX checkout>/src/fontMetricsData.js

KaTeX generates fontMetricsData.js from its fonts (buildMetrics.sh), so the
table must always come from the same KaTeX release as lib/katex_fonts/fonts.
"""
import json
import re
import sys

src_path = sys.argv[1]
version = sys.argv[2] if len(sys.argv) > 2 else 'unknown'
text = open(src_path, encoding='utf-8').read()
body = text[text.index('export default') + len('export default'):].strip()
body = body.rstrip().rstrip(';')
body = re.sub(r',(\s*[}\]])', r'\1', body)  # JSON forbids trailing commas
data = json.loads(body)


def num(value):
    if value == int(value):
        return f'{int(value)}' if value != 0 else '0'
    return repr(value)


out = [
    '// GENERATED by tool/gen_font_metrics.py from KaTeX '
    f'{version} src/fontMetricsData.js. DO NOT EDIT.',
    '//',
    '// Each entry: CharacterMetrics(depth, height, italic, skew, width), in em.',
    '',
    "import 'font_metrics.dart';",
    '',
    'const Map<String, Map<int, CharacterMetrics>> fontMetricsData = {',
]
for font, chars in data.items():
    out.append(f"  '{font}': {{")
    for code, metrics in sorted(chars.items(), key=lambda kv: int(kv[0])):
        assert len(metrics) == 5, (font, code, metrics)
        args = ', '.join(num(m) for m in metrics)
        out.append(f'    {int(code)}: CharacterMetrics({args}),')
    out.append('  },')
out.append('};')
out.append('')
sys.stdout.write('\n'.join(out))
