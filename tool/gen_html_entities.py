#!/usr/bin/env python3
"""Regenerates lib/src/html/html_entities.dart from the WHATWG entity list.

Usage: python3 tool/gen_html_entities.py entities.json > lib/src/html/html_entities.dart
(entities.json: https://html.spec.whatwg.org/entities.json)
"""
import json
import sys

data = json.load(open(sys.argv[1], encoding='utf-8'))


def dart_string(s):
    out = []
    for ch in s:
        cp = ord(ch)
        if ch in "\\'$":
            out.append('\\' + ch)
        elif 0x20 <= cp < 0x7F:
            out.append(ch)
        elif cp <= 0xFFFF:
            out.append(f'\\u{cp:04X}')
        else:
            out.append(f'\\u{{{cp:X}}}')
    return "'" + ''.join(out) + "'"


keys = sorted(data, key=lambda k: (-len(k), k))
lines = [
    '// GENERATED by tool/gen_html_entities.py from the WHATWG HTML entity',
    '// list (https://html.spec.whatwg.org/entities.json). DO NOT EDIT.',
    '',
    '/// Every named character reference, including the legacy forms without',
    '/// a trailing semicolon (`&amp`, `&nbsp`).',
    'const Map<String, String> htmlNamedEntities = {',
]
for k in keys:
    lines.append(f'  {dart_string(k)}: {dart_string(data[k]["characters"])},')
lines.append('};')
lines.append('')
lines.append(f'/// Length of the longest name in [htmlNamedEntities].')
lines.append(f'const int htmlEntityMaxLength = {max(len(k) for k in keys)};')
lines.append('')
sys.stdout.write('\n'.join(lines))
